(function () {
  var TITLE = { fr: document.title, en: 'Ndéye Fatou SOW — Software & Data Engineer' };
  var LABELS = {
    fr: { light: 'Passer en mode clair', dark: 'Passer en mode sombre', lang: 'Choisir la langue' },
    en: { light: 'Switch to light mode', dark: 'Switch to dark mode', lang: 'Choose language' }
  };
  var norm = function (s) { return s.replace(/\s+/g, ' ').trim(); };
  var save = function (k, v) { try { localStorage.setItem(k, v); } catch (e) {} };
  var load = function (k) { try { return localStorage.getItem(k); } catch (e) { return null; } };

  // On garde chaque texte français une seule fois, pour pouvoir y revenir.
  var slots = [];
  var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  var node;
  while ((node = walker.nextNode())) {
    var tag = node.parentNode.nodeName;
    if (tag === 'SCRIPT' || tag === 'STYLE') continue;
    if (EN[norm(node.nodeValue)]) slots.push({ node: node, fr: node.nodeValue });
  }
  var attrs = [];
  document.querySelectorAll('[alt],[aria-label]').forEach(function (el) {
    if (el.closest('.tools')) return;
    ['alt', 'aria-label'].forEach(function (a) {
      if (el.hasAttribute(a)) attrs.push({ el: el, name: a, fr: el.getAttribute(a) });
    });
  });

  var lang = 'fr';
  var langBtns = document.querySelectorAll('.lang-switch button');
  var themeBtn = document.getElementById('theme-btn');

  function paintThemeBtn() {
    var dark = document.documentElement.getAttribute('data-theme') === 'dark';
    var label = LABELS[lang][dark ? 'light' : 'dark'];
    themeBtn.setAttribute('aria-label', label);
    themeBtn.title = label;
    themeBtn.querySelector('use').setAttribute('href', dark ? '#i-sun' : '#i-moon');
  }

  function setLang(next) {
    lang = next;
    document.documentElement.lang = lang;
    document.title = TITLE[lang];
    slots.forEach(function (s) {
      if (lang === 'fr') { s.node.nodeValue = s.fr; return; }
      var lead = s.fr.match(/^\s*/)[0], tail = s.fr.match(/\s*$/)[0];
      s.node.nodeValue = lead + EN[norm(s.fr)] + tail;
    });
    attrs.forEach(function (a) {
      var t = lang === 'en' && EN[norm(a.fr)];
      a.el.setAttribute(a.name, t || a.fr);
    });
    langBtns.forEach(function (b) {
      b.setAttribute('aria-pressed', b.getAttribute('data-lang') === lang ? 'true' : 'false');
    });
    document.querySelector('.lang-switch').setAttribute('aria-label', LABELS[lang].lang);
    paintThemeBtn();
  }

  langBtns.forEach(function (b) {
    b.addEventListener('click', function () {
      var l = b.getAttribute('data-lang');
      save('lang', l);
      setLang(l);
    });
  });
  themeBtn.addEventListener('click', function () {
    var next = document.documentElement.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
    document.documentElement.setAttribute('data-theme', next);
    save('theme', next);
    paintThemeBtn();
  });

  // Un lien se terminant par ?lang=en ouvre directement le site en anglais.
  var fromUrl = new URLSearchParams(location.search).get('lang');
  setLang(fromUrl === 'en' || fromUrl === 'fr' ? fromUrl : (load('lang') === 'en' ? 'en' : 'fr'));
})();
